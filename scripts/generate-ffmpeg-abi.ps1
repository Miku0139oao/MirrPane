'@
    $sourcePath = Join-Path $taskTemp 'abi.c'
    $programPath = Join-Path $taskTemp 'abi.exe'
    Set-Content -LiteralPath $sourcePath -Value $source -Encoding utf8
    & $Compiler '-I' $Headers $sourcePath '-o' $programPath
    if ($LASTEXITCODE -ne 0) { throw 'ABI generator compilation failed' }
    $output = Join-Path $PSScriptRoot '..\backend\internal\decode\abi_windows_amd64.go'
    & $programPath | Set-Content -LiteralPath $output -Encoding utf8
    if ($LASTEXITCODE -ne 0) { throw 'ABI generator failed (requires Windows x64)' }
    & gofmt -w $output
    if ($LASTEXITCODE -ne 0) { throw 'gofmt failed' }
}
finally {
    # This directory was created with a new GUID directly under the OS temp directory.
    if ((Split-Path -Parent ([IO.Path]::GetFullPath($taskTemp))) -ne ([IO.Path]::GetTempPath()).TrimEnd('\')) {
        throw 'Unexpected generator temp directory'
    }
    Remove-Item -LiteralPath $taskTemp -Recurse -Force
}
