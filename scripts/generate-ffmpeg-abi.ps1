# Maintainer-only: regenerate the checked-in Windows x64 FFmpeg ABI definitions.
# Normal builds need neither these headers nor a C compiler.
param(
    [string]$Headers = "$PSScriptRoot\..\third_party\ffmpeg\include",
    [string]$Compiler = 'gcc'
)
$ErrorActionPreference = 'Stop'
$taskTemp = Join-Path ([IO.Path]::GetTempPath()) ([Guid]::NewGuid().ToString('N'))
New-Item -ItemType Directory -Path $taskTemp | Out-Null
try {
    $source = @'
