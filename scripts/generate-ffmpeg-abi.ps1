#include <stdio.h>
#include <stdlib.h>
#include <libavcodec/avcodec.h>
#include <libavutil/pixdesc.h>
#include <libswscale/swscale.h>
#include <libswresample/swresample.h>

static size_t position;
static const char *go_type;
static struct { const char *name; size_t offset; } fields[32];
static size_t field_count;
static void field(const char *name, const char *type, size_t offset, size_t size) {
    if (offset < position || field_count >= 32) {
        fprintf(stderr, "ABI fields changed order; update generator: %s.%s\n", go_type, name);
        exit(1);
    }
    if (offset > position) printf("    _ [%zu]byte\n", offset - position);
    printf("    %s %s\n", name, type);
    position = offset + size;
    fields[field_count].name = name;
    fields[field_count++].offset = offset;
}
static void assertions(size_t size) {
    printf("var _ [%zu - unsafe.Sizeof(%s{})]byte\n", size, go_type);
    printf("var _ [unsafe.Sizeof(%s{}) - %zu]byte\n", go_type, size);
    for (size_t i = 0; i < field_count; i++) {
        printf("var _ [%zu - unsafe.Offsetof(%s{}.%s)]byte\n", fields[i].offset, go_type, fields[i].name);
        printf("var _ [unsafe.Offsetof(%s{}.%s) - %zu]byte\n", go_type, fields[i].name, fields[i].offset);
    }
    printf("\n");
}
#define BEGIN(c, go) position = 0; field_count = 0; go_type = go; printf("type " go " struct {\n");
#define FIELD(c, member, go, type) field(go, type, offsetof(c, member), sizeof(((c*)0)->member));
